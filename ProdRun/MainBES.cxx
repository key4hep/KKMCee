double sqr( const double x ){ return x*x;};

double MyBESdist(const double &Ebeam1, const double &Ebeam2, const double ParBES[]){
///////////////////////////////////////////////////////////////////
// User defined BES external distribution,
// It can be replaced by any other one, including beamstrahlung.
// For the moment it is just copy of the internal BES defining function
// ParBes parameters are defined in the KKMCee input data,
// One may ignore them and replace with the user own input parameters
// Note: it will only be effective when one sets (in the input file):
//   25              1      KeyBES ..., =1 Gaussian without mapping, ...
///////////////////////////////////////////////////////////////////
  double dist,sigma1,sigma2,corho, E1,E2, delE1,delE2;
// Ebeam1 and Ebeam2 are beam energies generated by FOAM
// E1 and E2 are constant reference beam energies from input data
  E1 = ParBES[0];
  E2 = ParBES[1];
  sigma1= ParBES[2]*E1;  // gaussian dispersion beam1
  sigma2= ParBES[3]*E2;  // gaussian dispersion beam2
  corho = ParBES[4];     // gaussian correlation
  //[[[[[[[[[[[[
  //corho=0;   // for testing
  //]]]]]]]]]]]]
  delE1=Ebeam1-E1;
  delE2=Ebeam2-E2;
  dist = sqr(delE1/sigma1)+ sqr(delE2/sigma2)-2*corho*(delE1/sigma1)*(delE2/sigma2);
  dist = exp(-0.5/(1-sqr(corho))*dist);
  dist *= 1/(2.0*M_PI)/(sigma1*sigma2)/sqrt(1-sqr(corho)); // Normalization factor
  return dist;
};

/////////////////////////////////////////////////////////////
int main(int argc, char **argv){
//
//++++++++++++++++++++++++++++++++++++++++
TApplication theApp("theApp", &argc, argv);
//++++++++++++++++++++++++++++++++++++++++
//////////////////////////////////////////////////////////////
//       Setting up MC generator object
ofstream   OutFile("pro.output",ios::out);  // Logfile output
TFile *MCgenFile = new TFile("mcgen.root","RECREATE","Generators");
MCgenFile->cd();
TRandom3 *RN_gen = new TRandom3();// Central random numb. gen.
long iniseed = 54217137; RN_gen->SetSeed(iniseed);
//
KKee2f *KKMCgen = new KKee2f("MCgen"); // MC generator object
//
// Histogram encapsulating normalization of the MC run
int nb = 10000;
TH1D *h_NORMA= new TH1D("KKMCgen_NORMA","Normaliz. histo",nb,0,nb);
//
KKMCgen->Initialize( RN_gen, &OutFile, h_NORMA);  // Initialization
/////////////////////////////////////////////////////////////
// User defined BES distribution (set KeyBES =1 in the input file)
// If this is omitted then the default internal BES spectrum is used
KKMCgen->SetUserBESdist(MyBESdist);
/////////////////////////////////////////////////////////////
//  Booking his
TH1D *hst_wtmain  = new TH1D("hst_wtmain",  "WTmain            ",  100, 0 , 4.0);
TH1D *hst_acolin1 = new TH1D("hst_acolin1", "Acolinearity CEEX2",  100, 0 , 0.100);
TH1D *hst_acolin2 = new TH1D("hst_acolin2", "CEEX2-CCX1",          100, 0 , 0.100);
double delv = 0.007;
TH2D *sca_r1r2    = new TH2D("sca_r1r2" ,  "BES spectrum", 100, -delv , delv, 100, -delv , delv);
hst_acolin1->Sumw2(); hst_acolin2->Sumw2(); sca_r1r2->Sumw2();
KKevent  *Event = KKMCgen->m_Event;             // KKMC internal event
GenEvent *Hvent = (GenEvent*)KKMCgen->m_Hvent;  // HEPMC3 public event
/////////////////////////////////////////////////////////////
int NevGen =100;
cout<<"MainBES: ********************************** "<<endl;
cout<<"MainBES: type in no. of MC events: (100?) ";
cin>>NevGen; cout<<" requested "<< NevGen <<" events"<<endl;
/////////////////////////////////////////////////////////////
//            Loop over MC events
for(int iev=1; iev<=NevGen; iev++) {
   KKMCgen->Generate();
   if( (iev/10000)*10000 == iev || iev<=10) {
       cout<<"MaiBES: iev="<<iev<<endl;
       Event->EventPrintAll();  // printing out KKMCee event
       Event->EventPrintAll(&OutFile);
       Print::listing(*Hvent);  // printing out HEPMC3 event
       Print::content(*Hvent);
   }//if iev
   // ****************** Histogramming *********************
   double WtMain  = KKMCgen->m_WtMain;          // m_WtMain=WtCEEX2
   double WtCEEX1 = KKMCgen->m_WtAlter[202];    //  CEEX Weight O(alf1)
   double WtCEEX2 = KKMCgen->m_WtAlter[203];    //  CEEX Weight O(alf2)
   hst_wtmain->Fill(WtMain);
   TLorentzVector Qf1 = Event->m_Qf1; // final fermion (muon) four-momenta
   TLorentzVector Qf2 = Event->m_Qf2;
   double E1    = KKMCgen->m_ParBES[0];   // beam1 energy from input data
   double E2    = KKMCgen->m_ParBES[1];   // beam2 energy from input data
   double Ene1  = Event->m_Pf1.E();       // generated beam1 energy
   double Ene2  = Event->m_Pf2.E();       // generated beam2 energy
   double r1 = (Ene1 -E1)/E1;     // relative variation of beam1 energy
   double r2 = (Ene2 -E2)/E2;     // relative variation of beam2 energy
   sca_r1r2->Fill(r1, r2,  WtMain);
   // the same is recorded in Event->m_r1 and Event->m_r2
   double Theta1  = Qf1.Theta();
   double Theta2  = M_PI-Qf2.Theta();
   double Acolin  = fabs(Theta2-Theta1); // acolinearity
   hst_acolin1->Fill(Acolin,WtCEEX2);             // CEEX O(alf2)
   hst_acolin2->Fill(Acolin,WtCEEX2-WtCEEX1);     // CEEX O(alf2)-O(alf1)
   //if( iev<5) { cout<<"##### Theta1 ="<<Theta1 <<" Theta2 ="<<Theta2<<" Acolin ="<<Acolin<<endl;}// if iev
}// for iev
/////////////////////////////////////////////////////////////
KKMCgen->Finalize(); // final printout

/////////////////////////////////// PLOTTING ////////////////////////////////////////////
TKfig *TK = new TKfig();
TK->HisNorm1(h_NORMA, hst_acolin1); // renormalizing to [nb]
TK->HisNorm1(h_NORMA, hst_acolin2); // renormalizing to [nb]
TK->HisNorm2(h_NORMA, sca_r1r2);    // renormalizing to [nb]
//
TCanvas *cFigBES1 = new TCanvas("cFigBES1","FigBES2: general info ",  20,  20,    1000,  500);
cFigBES1->Divide( 2,  1);
cFigBES1->cd(1);
TString OptSurf= "lego2";
sca_r1r2->DrawCopy(OptSurf);
cFigBES1->cd(2);
hst_wtmain->DrawCopy("h");
cFigBES1->cd(0);
cFigBES1->Modified(); cFigBES1->Update();
cFigBES1->SaveAs("cFigBES1.pdf");
//
TCanvas *cFigBES2 = new TCanvas("cFigBES2","FigBES2: general info ", 120, 120,    1000,  500);
cFigBES2->Divide( 2,  1);
cFigBES2->cd(1);
gPad->SetLogy(); // !!!!!!
hst_acolin1->GetXaxis()->SetTitle("acolinearity");
hst_acolin1->DrawCopy("h");    //CEEX2
//
cFigBES2->cd(2);
TH1D *RATio  = TK->HstRatio("RATio",  hst_acolin2,  hst_acolin1, kBlack );
RATio->SetMaximum( 0.01); RATio->SetMinimum(-0.01);
RATio->SetTitle("(CEEX2-CEEX1)/CEEX2");
RATio->GetXaxis()->SetTitle("acolinearity");
RATio->SetStats(0);
RATio->DrawCopy("h");  // (CEEX2-CEEX1)/CEEX2
cFigBES2->cd(0);
cFigBES2->Modified(); cFigBES2->Update();
cFigBES2->SaveAs("cFigBES2.pdf");
//
/////////////////////////////////// END PLOTTING ///////////////////////////////////////

cout << "  |--------------------| "<<endl<<flush;
cout << "  |  MainBES  Ended    | "<<endl<<flush;
cout << "  |--------------------| "<<endl<<flush;
//
KKMCgen->Write("MCgen",TObject::kOverwrite);
RN_gen->Write("RN_gen",TObject::kOverwrite);
MCgenFile->Write();
MCgenFile->Close();
//++++++++++++++++++++++++++++++++++++++++
theApp.Run();
//++++++++++++++++++++++++++++++++++++++++

return 0;
}// main
